"""Run the experiment matrix E1-E10 and regenerate every report figure and table.

    python -m qsv2v.experiments                 # everything (E9's sweep is cached per run)
    python -m qsv2v.experiments --only e01 e04  # a subset
    python -m qsv2v.experiments --quick         # small, fast settings (smoke test)
    python -m qsv2v.experiments --fresh         # also re-simulate cached E9 runs

Outputs go to results/experiments/ (or --out): one folder per experiment, every
figure copied to figures/, and SUMMARY.md with each hypothesis and its verdict.
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import json
import shutil
import sys
import time
from pathlib import Path

from qsv2v.experiments.common import RESULTS

EXPERIMENTS = [
    "e01_eve_detection",
    "e02_channel_noise",
    "e03_distance_loss",
    "e04_cascade_efficiency",
    "e05_attack_success",
    "e06_crypto_timing",
    "e07_handshake_cost",
    "e08_message_size",
    "e09_network_scale",
    "e10_qkd_vs_pqc",  # last: quotes E3, E7, E8 and E9
]


def verdict(s) -> str:
    return {
        True: "Supported",
        False: "Not supported",
        "partly": "Partly supported",
        None: "Comparison (no yes/no test)",
    }[s]


def write_summary(out: Path, outcomes: list, quick: bool) -> None:
    lines = [
        "# Experiment results (E1–E10)",
        "",
        "Generated by `python -m qsv2v.experiments`" + (" --quick (smoke-test settings: "
        "numbers are NOT report quality)" if quick else "") + ".",
        "Every number below comes from the runs in this folder; each experiment folder holds "
        "data.csv, summary.csv, table.md, result.json and its figures.",
        "",
        "| # | Experiment | Hypothesis | Verdict | Finding |",
        "|---|---|---|---|---|",
    ]  # fmt: skip
    for o in outcomes:
        lines.append(f"| {o.key} | {o.title} | {o.hypothesis} | {verdict(o.supported)} | "
                     f"{o.finding} |")  # fmt: skip
    lines += ["", "## Figures", ""]
    for p in sorted((out / "figures").glob("*.png")):
        lines.append(f"- [{p.name}](figures/{p.name})")
    (out / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (out / "summary.json").write_text(
        json.dumps([o.__dict__ for o in outcomes], indent=1, default=float), encoding="utf-8"
    )


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--only", nargs="+", help="experiment keys, e.g. e01 e09")
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--fresh", action="store_true", help="re-simulate cached E9 runs")
    ap.add_argument("--workers", type=int, default=None, help="E9 worker processes")
    ap.add_argument("--out", type=Path, default=RESULTS)
    args = ap.parse_args(argv)

    names = [n for n in EXPERIMENTS if not args.only or n[:3] in [k.lower()[:3] for k in args.only]]
    if not names:
        ap.error("no experiment matches --only")
    out = args.out
    figs = out / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    outcomes = []
    for name in names:
        mod = importlib.import_module(f"qsv2v.experiments.{name}")
        kw = {"base": out, "quick": args.quick}
        params = inspect.signature(mod.run).parameters
        if "fresh" in params:
            kw.update(fresh=args.fresh, workers=args.workers)
        print(f"{name} ...", flush=True)
        t0 = time.time()
        o = mod.run(**kw)
        print(f"  {o.key}: {verdict(o.supported)} ({time.time() - t0:.0f} s)\n  {o.finding}",
              flush=True)  # fmt: skip
        for p in (out / name).glob("figure*.png"):
            shutil.copy(p, figs / f"{name.split('_')[0].upper()}{p.stem[6:]}.png")
        outcomes.append(o)
    # Keep verdicts of experiments not re-run this time, so SUMMARY.md stays complete.
    from qsv2v.experiments.common import Outcome

    done = {o.key for o in outcomes}
    for name in EXPERIMENTS:
        rj = out / name / "result.json"
        if name not in names and rj.exists():
            o = Outcome(**json.loads(rj.read_text("utf-8")))
            if o.key not in done:
                outcomes.append(o)
    outcomes.sort(key=lambda o: int(o.key[1:]))
    write_summary(out, outcomes, args.quick)
    print(f"\nwrote {out / 'SUMMARY.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
